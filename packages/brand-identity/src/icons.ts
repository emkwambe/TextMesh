// ============ ICON SVG GENERATOR ============

export function generateIconSVG(
  name: IconName,
  props: IconProps = {}
): string {
  const { size = 24, color = 'currentColor', strokeWidth = 2 } = props;
  const path = ICONS[name];

  if (!path) {
    console.warn(`Icon "${name}" not found`);
    return '';
  }

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${path}</svg>`;
}

// ============ ICON DATA URL GENERATOR ============

export function getIconDataURL(
  name: IconName,
  props: IconProps = {}
): string {
  const svg = generateIconSVG(name, props);
  const encoded = encodeURIComponent(svg);
  return `data:image/svg+xml,${encoded}`;
}

// ============ ICON SPRITE GENERATOR ============

export function generateIconSprite(): string {
  const symbols = Object.entries(ICONS)
    .map(
      ([name, path]) => `
  <symbol id="icon-${name}" viewBox="0 0 24 24">
    ${path}
  </symbol>`
    )
    .join('');

  return `<svg xmlns="http://www.w3.org/2000/svg" style="display: none;">
  ${symbols}
</svg>`;
}

// ============ ICON USAGE HELPER ============

export function useIcon(name: IconName): string {
  return `<svg><use href="#icon-${name}"></use></svg>`;
}

